export let getStandardTextureRect = function (textureSize, spriteIndex, width, height) {
	return new Rect(
		spriteIndex * width % textureSize.width,
		Math.floor(spriteIndex * width / textureSize.width) * height,
		width,
		height,
	);
};

export let getItemRect = function (item, offset = 0, spriteIndex = null) {
	offset += +(spriteIndex ?? item.spriteIndex);
	let textureSize = textureSizes[item.texture];
	
	if (!item.isError) {
		switch (item.itemType) {
		case 'BC':
		case 'M':
			return getStandardTextureRect(textureSize, offset, 16, 32);
		
		case 'F': {
			// See StardewValley.Objects.Furniture:getDefaultSourceRectForType()
			
			let size = [1, 2];
			
			if (item.data[2] !== '-1') {
				size = item.data[2].split(/ +/g);
			}
			else {
				let typeName = item.data[1].toLowerCase();
				
				if (!/^bed/.test(typeName)) {
					switch (typeName) {
					case 'bench': size = [2, 2]; break;
					case 'couch': size = [3, 2]; break;
					case 'armchair': size = [2, 2]; break;
					case 'dresser': size = [2, 2]; break;
					case 'long table': size = [5, 3]; break;
					case 'painting': size = [2, 2]; break;
					case 'bookcase': size = [2, 3]; break;
					case 'table': size = [2, 3]; break;
					case 'rug': size = [3, 2]; break;
					case 'fireplace': size = [2, 5]; break;
					}
				}
			}
			
			return new Rect(
				offset * 16 % textureSize.width,
				Math.floor(offset * 16 / textureSize.width) * 16,
				+size[0] * 16,
				+size[1] * 16,
			);
		}
		
		case 'FL':
			return new Rect(
				offset % 8 * 32,
				Math.floor(offset / 8) * 32 + ((item.data.Id == null) ? 336 : 0),
				28,
				26,
			);
		
		case 'WP':
			return new Rect(
				offset % 16 * 16,
				Math.floor(offset / 16) * 48 + 8,
				16,
				28,
			);
		
		case 'H':
			return new Rect(
				offset * 20 % textureSize.width,
				Math.floor(offset * 20 / textureSize.width) * 20 * 4,
				20,
				20,
			);
		
		case 'P':
			return new Rect(
				192 * (offset % Math.floor(textureSize.width / 192)),
				688 * Math.floor(offset / Math.floor(textureSize.width / 192)) + 672,
				16,
				16,
			);
		
		case 'S':
			return new Rect(
				offset * 8 % Math.floor(textureSize.width / 2),
				Math.floor(offset * 8 / Math.floor(textureSize.width / 2)) * 32,
				8,
				8,
			);
		}
	}
	
	return getStandardTextureRect(textureSize, offset, 16, 16);
};

export let getItemText = function (item, stack = 1, quality = 0, nameOverride = null) {
	let text = nameOverride ?? item.displayName;
	
	if (item.isError && item.itemType === 'O') {
		switch (item.itemId) {
		case '-1':
			text = 'Gold Coin';
			quality = 0;
			break;
		
		case '-5':
			text = 'Any Egg';
			break;
		
		case '-6':
			text = 'Any Milk';
			break;
		}
	}
	
	let qualityName = getQualityName(quality);
	
	if (qualityName != '') {
		text = `${qualityName} ${text}`;
	}
	
	if (stack != 1) {
		text += ` (${stack})`;
	}
	
	return text;
};

