//== Element Details ==//

// These functions facilitate converting XML DOM elements into native
// plain object data structures. This has limitations common to other
// XML-to-JSON converters, but it should be able to properly handle
// Stardew Valley's XML, and it's usually easier to work with than using
// DOM/jQuery methods.
//
// An element can be represented in either a "root" structure or a
// "non-root" structure. A root structure has the tag name, attributes,
// and child elements all within one object. Example with element
// children:
//
// {
//   '@@': 'NPC',         // (Tag name)
//   '@xsi:type': 'Pet',  // (Attribute)
//   name: 'Miso',        // (Child element with text)
//   Position: { ... },   // (Child element with element children)
//   'datingFarmer@xsi:nil': 'true',  // (Child element's attribute)
//   datingFarmer: '',    // (Child element with text)
//   ...(other children)...
// }
// 
// Example with no element children (text content only):
//
// {
//   '@@': 'tagName',
//   '@attrName: 'value',
//   '$': 'Text content',
// }
//
// A non-root structure puts its child elements inside an inner object
// and puts the attributes outside that object, prefixed with the tag
// name. Example with element children:
//
// {
//   'NPC@xsi:type': 'Pet',
//   NPC: {
//     name: 'Miso',
//     Position: { ... },
//     'datingFarmer@xsi:nil': 'true',
//     datingFarmer: '',
//   },
//   ...(siblings)...
// }
//
// Example with no element children (text content only):
//
// {
//   'tagName@attrName': 'value',
//   tagName: 'Text content',
//   ...(siblings)...
// }
//
// Generally, the root structure is used for the top-level element,
// while the non-root structure is used for its descendents. When
// passing a subtree to another function, it's usually a good idea to
// pass a "rooted" version of the subtree via rootDetails(). This allows
// the function to see the tag name and attributes of the subtree's
// top-level element, and basically handle it like a complete tree.
//
// If an element has multiple children with the same tag name, only the
// first instance (and its attributes) will be directly exposed. The
// rest are stored in the special "+" property, in root structures. The
// best way to access all instances is using getDetailsMultiple(), which
// yields each instance, in root structures.
//
// All primitive values in details are expected to be strings, since
// they represent raw text content and attribute values in an XML
// document. If you try to store other value types in a details
// structure, it may have unexpected results.

export let getElementDetails = function (element, options = {}, depth = 0) {
	let details = {};
	let prefixes = options.prefixes ?? nsPrefixes;
	let tagName = (element.prefix === null) ? element.tagName : `${prefixes?.[element.namespaceURI] ?? element.prefix}:${element.localName}`;
	details['@@'] = tagName;
	
	for (let attr of element.attributes) {
		let attrName = (attr.prefix === null) ? attr.name : `${prefixes?.[attr.namespaceURI] ?? attr.prefix}:${attr.localName}`;
		details[`@${attrName}`] = attr.value;
	}
	
	if (element.childElementCount === 0) {
		details.$ = element.textContent;
	}
	else {
		++depth;
		let includeChildren = options.includeChildren ?? null;
		let excludeChildren = options.excludeChildren ?? [];
		let childOptions = (includeChildren === null && excludeChildren.length === 0) ? options : {
			...options,
			includeChildren: null,
			excludeChildren: [],
		};
		
		for (let child of element.children) {
			let childTagName = (child.prefix === null) ? child.tagName : `${prefixes?.[child.namespaceURI] ?? child.prefix}:${child.localName}`;
			
			if ((includeChildren === null || includeChildren.includes(childTagName)) && !excludeChildren.includes(childTagName)) {
				addDetail(details, getElementDetailsNonRoot(child, childOptions, depth), childTagName);
			}
		}
	}
	
	return details;
};

export let getElementDetailsNonRoot = function (element, options = {}, depth = 0) {
	let details = {};
	let prefixes = options.prefixes ?? nsPrefixes;
	let tagName = (element.prefix === null) ? element.tagName : `${prefixes?.[element.namespaceURI] ?? element.prefix}:${element.localName}`;
	
	for (let attr of element.attributes) {
		let attrName = (attr.prefix === null) ? attr.name : `${prefixes?.[attr.namespaceURI] ?? attr.prefix}:${attr.localName}`;
		details[`${tagName}@${attrName}`] = attr.value;
	}
	
	if (element.childElementCount === 0) {
		details[tagName] = element.textContent;
	}
	else {
		let childDetails = {};
		details[tagName] = childDetails;
		++depth;
		let includeChildren = options.includeChildren ?? null;
		let excludeChildren = options.excludeChildren ?? [];
		let childOptions = (includeChildren === null && excludeChildren.length === 0) ? options : {
			...options,
			includeChildren: null,
			excludeChildren: [],
		};
		
		for (let child of element.children) {
			let childTagName = (child.prefix === null) ? child.tagName : `${prefixes?.[child.namespaceURI] ?? child.prefix}:${child.localName}`;
			
			if ((includeChildren === null || includeChildren.includes(childTagName)) && !excludeChildren.includes(childTagName)) {
				addDetail(childDetails, getElementDetailsNonRoot(child, childOptions, depth), childTagName);
			}
		}
	}
	
	return details;
};

export let addDetail = function (details, entry, unrootedTagName = null) {
	let tagName = unrootedTagName ?? entry['@@'];
	
	if (!Object.hasOwn(details, tagName)) {
		Object.assign(details, unrootedTagName === null ? unrootDetails(entry) : entry);
	}
	else {
		if (!Object.hasOwn(details, '+')) {
			details['+'] = {};
		}
		
		if (!Object.hasOwn(details['+'], tagName)) {
			details['+'][tagName] = [];
		}
		
		details['+'][tagName].push(unrootedTagName === null ? entry : rootDetails(entry, tagName));
	}
};

export let deleteDetail = function (details, tagName) {
	if (details == null) {
		return;
	}
	
	delete details[tagName];
	
	let searchKey = tagName + '@';
	
	for (let key of Object.keys(details)) {
		if (key.startsWith(searchKey)) {
			delete details[key];
		}
	}
	
	if (Object.hasOwn(details, '+') && Object.hasOwn(details['+'], tagName)) {
		delete details['+'][tagName];
		
		if (Object.keys(details['+']).length === 0) {
			delete details['+'];
		}
	}
};

export let getDetailsMultiple = function* (details, tagName) {
	if (details == null || !Object.hasOwn(details, tagName)) {
		return;
	}
	
	let entry = {'@@': tagName};
	let searchKey = tagName + '@';
	
	for (let [key, value] of Object.entries(details)) {
		if (key.startsWith(searchKey)) {
			entry[key.substring(tagName.length)] = value;
		}
	}
	
	let childDetails = details[tagName];
	
	if (typeof childDetails === 'string') {
		entry.$ = childDetails;
	}
	else {
		Object.assign(entry, unrootDetails(childDetails));
	}
	
	yield entry;
	
	if (Object.hasOwn(details, '+') && Object.hasOwn(details['+'], tagName)) {
		yield* details['+'][tagName];
	}
};

export let countDetails = function (details, tagName) {
	if (details == null || !Object.hasOwn(details, tagName)) {
		return 0;
	}
	
	if (Object.hasOwn(details, '+') && Object.hasOwn(details['+'], tagName)) {
		return details['+'][tagName].length + 1;
	}
	
	return 1;
};

export let rootDetails = function (details, tagName) {
	if (details == null || !Object.hasOwn(details, tagName)) {
		return null;
	}
	
	let rooted = {'@@': tagName};
	let searchKey = tagName + '@';
	
	for (let [key, value] of Object.entries(details)) {
		if (key.startsWith(searchKey)) {
			rooted[key.substring(tagName.length)] = value;
		}
	}
	
	let childDetails = details[tagName];
	
	if (typeof childDetails === 'string') {
		rooted.$ = childDetails;
	}
	else {
		Object.assign(rooted, childDetails);
	}
	
	return rooted;
};

export let unrootDetails = function (details) {
	if (!Object.hasOwn(details, '@@')) {
		// Already a non-root structure.
		
		return details;
	}
	
	let tagName = details['@@'];
	let unrooted = {};
	let children = {};
	
	for (let [key, value] of Object.entries(details)) {
		if (key.startsWith('@')) {
			if (key !== '@@') {
				unrooted[tagName + key] = value;
			}
		}
		else {
			children[key] = value;
		}
	}
	
	unrooted[tagName] = details.$ ?? children;
	return unrooted;
};

export let nilOrDetails = function (details) {
	return (details == null || details['@xsi:nil'] === 'true') ? null : details;
};

export let nilOrRootDetails = function (details, tagName) {
	if (details == null || details[`${tagName}@xsi:nil`] === 'true') {
		return null;
	}
	
	return rootDetails(details, tagName);
};

export let detailsToXML = function (details, depth = 0) {
	details = unrootDetails(details);
	let xml = '';
	let indent = '  '.repeat(depth);
	
	for (let [key, value] of Object.entries(details)) {
		if (!['', '+'].includes(key) && !key.includes('@')) {
			xml += indent + `<${key}`;
			let searchKey = key + '@';
			
			for (let [key2, value2] of Object.entries(details)) {
				if (key2.startsWith(searchKey)) {
					xml += ' ' + key2.substring(searchKey.length) + '="' + escapeHTML(value2) + '"';
				}
			}
			
			xml += '>';
			
			if (!(value instanceof Object)) {
				xml += escapeHTML(value);
			}
			else if (value.$ != null) {
				xml += escapeHTML(value.$);
			}
			else {
				xml += '\n' + detailsToXML(value, depth + 1) + indent;
			}
			
			xml += `</${key}>\n`;
			
			if (Object.hasOwn(details, '+') && Object.hasOwn(details['+'], key)) {
				for (let entry of details['+'][key]) {
					xml += detailsToXML(entry, depth);
				}
			}
		}
	}
	
	return xml;
};

