export let Rect = class {
	x;
	y;
	width;
	height;
	
	constructor (x = 0, y = 0, width = 0, height = 0) {
		this.x = +x;
		this.y = +y;
		this.width = +width;
		this.height = +height;
	}
	
	contains (x, y) {
		return x >= this.x && y >= this.y && x < this.x + this.width && y < this.y + this.height;
	}
	
	centerX () {
		return this.x + this.width / 2;
	}
	
	centerY () {
		return this.y + this.height / 2;
	}
	
	* getPoints () {
		let point = [0, 0];
		
		for (let y = 0; y < this.height; ++y) {
			point[1] = this.y + y;
			
			for (let x = 0; x < this.width; ++x) {
				point[0] = this.x + x;
				yield point;
			}
		}
	}
	
	static from (rect) {
		if (rect == null) {
			return null;
		}
		
		return new Rect(
			rect.x ?? rect.X ?? rect[0],
			rect.y ?? rect.Y ?? rect[1],
			rect.width ?? rect.Width ?? rect[2],
			rect.height ?? rect.Height ?? rect[3],
		);
	}
};

