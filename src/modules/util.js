export let getTintFilter = function (r, g, b, share = true, linear = false) {
	// share=false prevents the color from being added to the cache. This
	// may be useful in situations where we anticipate a large number of
	// distinct (and maybe even temporary) colors with negligible reuse.
	
	r = Math.round(r);
	g = Math.round(g);
	b = Math.round(b);
	
	if (r === 255 && g === 255 && b === 255) {
		return null;
	}
	
	let id = `shared-filter-tint-${r}-${g}-${b}-${linear ? 1 : 0}`;
	
	if (document.getElementById(id) == null) {
		// No tint filter exists yet for this color. Prepare one.
		
		let filter = document.createElementNS('http://www.w3.org/2000/svg', 'filter');
		filter.setAttribute('id', id);
		filter.setAttribute('x', 0);
		filter.setAttribute('y', 0);
		let feColorMatrix = document.createElementNS('http://www.w3.org/2000/svg', 'feColorMatrix');
		feColorMatrix.setAttribute('type', 'matrix');
		
		if (!linear) {
			feColorMatrix.setAttribute('color-interpolation-filters', 'sRGB');
		}
		
		feColorMatrix.setAttribute('values', `
			${(r / 255).toFixed(4)} 0 0 0 0
			0 ${(g / 255).toFixed(4)} 0 0 0
			0 0 ${(b / 255).toFixed(4)} 0 0
			0 0 0 1 0`);
		filter.appendChild(feColorMatrix);
		
		if (!share) {
			let svg = `<svg xmlns="http://www.w3.org/2000/svg">${filter.outerHTML}</svg>`;
			return `url("data:image/svg+xml;base64,${window.btoa(svg)}#${id}")`;
		}
		
		$('#shared-filter-effects').append(filter);
	}
	
	return `url("#${id}")`;
};

export let escapeHTML = function (string) {
	return (string + '')
		.replace(/&/g, '&amp;')
		.replace(/"/g, '&quot;')
		.replace(/'/g, '&apos;')
		.replace(/</g, '&lt;');
};

