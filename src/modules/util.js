export let stringToColor = function (rawColor) {
	rawColor = rawColor?.trim();
	
	if (rawColor == null || rawColor === '') {
		return null;
	}
	
	if (rawColor.startsWith('#')) {
		let value = parseInt(rawColor.substring(1), 16);
		
		if (isNaN(value)) {
			return null;
		}
		else if (rawColor.length === 7) {
			return [(value >>> 16) & 0xff, (value >>> 8) & 0xff, value & 0xff, 255];
		}
		else if (rawColor.length === 9) {
			return [(value >>> 24) & 0xff, (value >>> 16) & 0xff, (value >>> 8) & 0xff, value & 0xff];
		}
	}
	else if (rawColor.includes(' ')) {
		let parts = rawColor.split(/ +/);
		
		if (parts.length === 3) {
			return [+parts[0], +parts[1], +parts[2], 255];
		}
		else if (parts.length === 4) {
			return [+parts[0], +parts[1], +parts[2], +parts[3]];
		}
	}
	else {
		return Object.hasOwn(namedColors, rawColor) ? namedColors[rawColor] : null;
	}
	
	return null;
};

export let serializeColor = function (color) {
	return {
		B: color[2] + '',
		G: color[1] + '',
		R: color[0] + '',
		A: (color[3] ?? 255) + '',
		PackedValue: ((color[3] ?? 255) * 16777216 + ((color[2] << 16) | (color[1] << 8) | color[0])) + '',
	};
};
