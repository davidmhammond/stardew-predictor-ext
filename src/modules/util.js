export let nextBool = function (rng, chance = .5) {
	if (chance >= 1) {
		return true; // Don't update the RNG.
	}
	
	return rng.NextDouble() < chance;
};

export let choose = function (rng, choices) {
	return choices[rng.Next(choices.length)];
};

export let shuffle = function (rng, list) {
	// See StardewValley.Utility:Shuffle()
	
	let j = list.length;
	
	while (j > 1) {
		let i = rng.Next(j--);
		let temp = list[j];
		list[j] = list[i];
		list[i] = temp;
	}
};

