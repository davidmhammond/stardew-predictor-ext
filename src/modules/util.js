export let parseItemId = function (qualifiedItemId) {
	if (qualifiedItemId != null) {
		let match = qualifiedItemId.match(/^\(([^)]+)\)(.+)/);
		
		if (match) {
			return [match[1], match[2]];
		}
	}
	
	return null;
};

export let convertOldItemType = function (oldItemType, itemId) {
	switch (oldItemType) {
	case 'Furniture':
		return 'F';
	
	case 'Object':
	case 'Ring':
	case 'R':
	case 'Blueprint':
	case 'BL':
		return 'O';
	
	case 'BigObject':
	case 'BO':
	case 'BigBlueprint':
	case 'BBl':
	case 'BBL':
		return 'BC';
	
	case 'Boot':
		return 'B';
	
	case 'Weapon':
		return 'W';
	
	case 'Hat':
		return 'H';
	
	case 'C':
		return (+itemId) >= 1000 ? 'S' : 'P';
	
	default:
		return oldItemType;
	}
};

